// mockEthClient is a mock implementation of ethclient.Client for testing
type mockEthClient struct {
	callContractFunc func(ctx context.Context, msg ethereum.CallMsg, blockNumber *big.Int) ([]byte, error)
}

func (m *mockEthClient) CallContract(ctx context.Context, msg ethereum.CallMsg, blockNumber *big.Int) ([]byte, error) {
	if m.callContractFunc != nil {
		return m.callContractFunc(ctx, msg, blockNumber)
	}
	return nil, errors.New("callContractFunc not set")
}

// TestMulticall3Executor_SingleCall tests execution of a single call
func TestMulticall3Executor_SingleCall(t *testing.T) {
	chainID := uint64(1)
	multicallAddress := common.HexToAddress("0xcA11bde05977b3631167028862bE2a173976CA11") // Standard Multicall3 address

	// Mock client that returns a successful result
	mockClient := &mockEthClient{
		callContractFunc: func(ctx context.Context, msg ethereum.CallMsg, blockNumber *big.Int) ([]byte, error) {
			// Multicall3 aggregate returns Result[] where Result is (bool success, bytes returnData)
			// For a single successful call, we return: success=true, returnData=0x1234
			// Encoding: (bool, bytes) = true, [0x12, 0x34]
			// ABI encoding: offset to data (32 bytes) + length (32 bytes) + data (32 bytes padded)
			// Simplified: we'll return properly encoded ABI data
			result := []byte{
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, // offset to first result
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, // success = true
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02, // returnData length = 2
				0x12, 0x34, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
				0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // returnData = [0x12, 0x34]
			}
			return result, nil
		},
	}

	executor := NewMulticall3Executor(chainID, multicallAddress, mockClient)

	target := common.HexToAddress("0x1234567890123456789012345678901234567890")
	callData := []byte{0x01, 0x02, 0x03}
	callID := "test-call-1"

	call := Call{
		Target:   target,
		CallData: callData,
		CallID:   callID,
	}

	results, err := executor.Execute(context.Background(), []Call{call})
	if err != nil {
		t.Fatalf("Execute failed: %v", err)
	}

	if len(results) != 1 {
		t.Errorf("expected 1 result, got %d", len(results))
	}

	result, exists := results[callID]
	if !exists {
		t.Fatalf("result for callID %s not found", callID)
	}

	// Verify result matches expected returnData
	expected := []byte{0x12, 0x34}
	if len(result) != len(expected) {
		t.Errorf("expected result length %d, got %d", len(expected), len(result))
	}
	for i := range expected {
		if result[i] != expected[i] {
			t.Errorf("expected result[%d] = %d, got %d", i, expected[i], result[i])
		}
	}
}

